/**
 * Workers - Local
 */

import type { WorkerRequest } from '../workerTypes.js'
import type { RenderAllData } from '@alanizcreative/formation-static/render/renderTypes.js'
import { WorkerEntrypoint } from 'cloudflare:workers'
import { serverlessRender } from '@alanizcreative/formation-static/serverless/serverless.js'
import { setStore, setStoreData } from '@alanizcreative/formation-static/store/store.js'
import { getAllLocalData } from '@alanizcreative/formation-static/local/localData.js'
import { workerProtectSetup } from '../workerSetup.js'
import { setPostsData } from '../../setup/setupData.js'
import { storeArgs } from '../../store/store.js'
import { config } from '../../config/config.js'
import { filters } from '../../filters/filters.js'
/* eslint-disable-next-line @typescript-eslint/ban-ts-comment */
// @ts-ignore - generated by setupLocal
import localData from '../../../lib/local/data.json'
/* eslint-disable-next-line @typescript-eslint/ban-ts-comment */
// @ts-ignore - generated by build
import imageMeta from '../../../lib/store/imageMeta.json'

/**
 * Get all data from data.json and store it for render.
 *
 * @return {Promise<RenderAllData>}
 */
const getData = async (): Promise<RenderAllData> => {
  const data = await getAllLocalData()

  if (!data) {
    throw new Error('No local data')
  }

  setPostsData(data)
  setStoreData(data) // Render skips storing when given serverless data

  return data
}

/**
 * Render pages on request for local development.
 */
export default class extends WorkerEntrypoint<SiteBindings> {
  /**
   * Route serverless and serve assets.
   *
   * @param {WorkerRequest} request
   * @return {Promise<Response>}
   */
  override async fetch (request: WorkerRequest): Promise<Response> {
    const url = new URL(request.url)
    const { pathname } = url

    /* Assets */

    if (request.method !== 'GET' || /\.\w+$/.test(pathname)) {
      return await this.env.ASSETS.fetch(request)
    }

    /* Pages */

    filters.cacheData = async () => await Promise.resolve({
      items: [],
      data: localData
    })

    workerProtectSetup(this.env)
    setStore({ ...storeArgs, imageMeta })

    config.env.cache = true

    return await serverlessRender(getData, {
      path: pathname.endsWith('/') ? pathname : `${pathname}/`,
      query: Object.fromEntries(url.searchParams)
    })
  }
}
